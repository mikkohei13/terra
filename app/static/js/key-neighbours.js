export function neighbourClass(a, b) {
    if (a === b) {
        return "same";
    }
    const left = NEIGHBOURS[a];
    if (!left) {
        return "other";
    }
    if (left.h.includes(b)) {
        return "h";
    }
    if (left.v.includes(b)) {
        return "v";
    }
    if (left.d.includes(b)) {
        return "d";
    }
    return "other";
}

